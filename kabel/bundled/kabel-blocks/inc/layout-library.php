                wp_die( esc_html__( 'You are not allowed to preview layouts.', 'kabel-blocks' ) );
        }
        check_admin_referer( 'kbl_preview_layout' );

        $slug = isset( $_GET['layout'] ) ? sanitize_key( (string) wp_unslash( $_GET['layout'] ) ) : '';
        $all  = kabel_block_layouts();
        if ( '' === $slug || ! isset( $all[ $slug ] ) ) {
                wp_die( esc_html__( 'Unknown layout.', 'kabel-blocks' ) );
        }

        $label = $all[ $slug ]['label'];

        /* Media: whatever the library already holds (bootstrapped sites show
         * real photos; fresh ones show the structure). No sideloads here. */
