/**
 * The thumbnail for one layout card.
 *
 * Prefers the REAL screenshot (assets/img/layouts/{slug}.webp — captured
 * from the live layout preview, regenerated by the build pipeline); the
 * wireframe SVG stays as the zero-asset fallback so the gallery never
 * breaks when the images are stripped.
 *
 * @param string $slug Layout slug.
 * @return string HTML (escaped <img> or the inline SVG).
 */
function kbl_library_thumb( string $slug ): string {
        $file = KABEL_BLOCKS_DIR . 'assets/img/layouts/' . $slug . '.webp';
        if ( is_readable( $file ) ) {
                $label = '';
                $all   = function_exists( 'kabel_block_layouts' ) ? kabel_block_layouts() : array();
                if ( isset( $all[ $slug ]['label'] ) ) {
                        $label = (string) $all[ $slug ]['label'];
                }
                return sprintf(
                        '<img class="kbl-library-photo" src="%s" alt="%s" width="800" height="537" loading="lazy" decoding="async">',
                        esc_url( KABEL_BLOCKS_URI . 'assets/img/layouts/' . $slug . '.webp' ),
                        esc_attr( $label ? $label : $slug )
                );
        }
        return kbl_library_thumb_svg( $slug );
}

