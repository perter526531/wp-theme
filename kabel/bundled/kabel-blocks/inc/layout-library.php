/**
 * Create a draft page pre-filled with the chosen layout, then jump into
 * the editor. Sample media is sideloaded on the way (kabel_seed_page).
 */
function kbl_handle_create_layout(): void {
        if ( ! current_user_can( 'edit_pages' ) ) {
                wp_safe_redirect( add_query_arg( 'kbl_library_error', 'caps', admin_url( 'admin.php?page=kabel-layout-library' ) ) );
                exit;
        }
        check_admin_referer( 'kbl_create_layout' );

        $slug = isset( $_GET['layout'] ) ? sanitize_key( (string) wp_unslash( $_GET['layout'] ) ) : '';
        $all  = kabel_block_layouts();

        if ( '' === $slug || ! isset( $all[ $slug ] ) ) {
                wp_safe_redirect( add_query_arg( 'kbl_library_error', 'unknown', admin_url( 'admin.php?page=kabel-layout-library' ) ) );
                exit;
        }

        /* kabel_seed_page() writes block markup through $wpdb and therefore
         * requires unfiltered_html (administrators on single-site installs). */
        if ( ! current_user_can( 'unfiltered_html' ) ) {
                wp_safe_redirect( add_query_arg( 'kbl_library_error', 'unfiltered', admin_url( 'admin.php?page=kabel-layout-library' ) ) );
                exit;
        }

        $label = $all[ $slug ]['label'];
        /* Every layout label is "Page — description"; the page title is the
         * first segment. explode() keeps the multibyte em-dash intact (a
         * byte-mode regex would truncate it and produce invalid UTF-8). */
        $parts = explode( ' — ', $label );
        $title = trim( (string) $parts[0] );
        if ( '' === $title ) {
                $title = $label;
        }

        $post_id = wp_insert_post(
                array(
                        'post_type'    => 'page',
                        'post_status'  => 'draft',
                        'post_title'   => $title,
                        'post_name'    => $slug,
                        'post_content' => '',
                ),
                true
        );

        if ( is_wp_error( $post_id ) || $post_id < 1 ) {
                wp_safe_redirect( add_query_arg( 'kbl_library_error', 'insert', admin_url( 'admin.php?page=kabel-layout-library' ) ) );
                exit;
        }

        $result = kabel_seed_page( (int) $post_id, $slug );

        if ( is_wp_error( $result ) ) {
                wp_safe_redirect( add_query_arg( 'kbl_library_error', 'seed', admin_url( 'admin.php?page=kabel-layout-library' ) ) );
                exit;
        }

        $editor = get_edit_post_link( $post_id, 'raw' );
        if ( ! $editor ) {
                $editor = add_query_arg( 'kbl_library_created', '1', admin_url( 'edit.php?post_type=page' ) );
        } else {
                $editor = add_query_arg( 'kbl_library_created', '1', $editor );
        }
        wp_safe_redirect( $editor );
        exit;
}
add_action( 'admin_post_kbl_create_layout', 'kbl_handle_create_layout' );
